CREATE DATABASE IF NOT EXISTS `Event_check_in_check_out`
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE `Event_check_in_check_out`;

CREATE TABLE IF NOT EXISTS doorlist_guests (
  code VARCHAR(40) NOT NULL PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  email VARCHAR(320) NOT NULL DEFAULT '',
  ticket VARCHAR(100) NOT NULL DEFAULT 'General',
  checked_in_at BIGINT UNSIGNED NULL,
  checked_out_at BIGINT UNSIGNED NULL,
  created_at BIGINT UNSIGNED NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS doorlist_event (
  id TINYINT UNSIGNED NOT NULL PRIMARY KEY,
  name VARCHAR(80) NOT NULL
) ENGINE=InnoDB;
